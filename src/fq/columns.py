"""Which `metrics` step writes which column: the map an agent needs before touching a column name.

The steps of `fq.metrics.calculate_metrics` are plain functions that add columns to the frame. This module runs the
pipeline once with each step wrapped, records the columns it added, and writes them as a catalogue
(`docs/columns.md`). It changes nothing in `metrics/` (so `evaluate.method_fingerprint()` is untouched) and nothing
imports it, so it can never alter a score.

    uv run python -m fq.columns                     # docs/columns.md from the first 200 companies of the cache
    uv run python -m fq.columns --rows 500 --out other.md

Columns per period are shown once, with `<p>` for the period (`ROIC_TTM`, `ROIC_Y0`, ... -> `ROIC_<p>`).
"""

from __future__ import annotations

import argparse
import functools
import re
from contextlib import ExitStack
from pathlib import Path
from unittest import mock

import pandas as pd

import fq.metrics as metrics_pkg
from fq.settings import Settings

PERIOD = re.compile(r"_(TTM|Y\d+|Q\d+)$")
INLINE = "calculate_metrics (inline)"


def generic(column: str) -> str:
    """`ROIC_Y0` -> `ROIC_<p>`: one entry for a column that exists in every period."""
    return PERIOD.sub("_<p>", column)


def trace(raw: pd.DataFrame, cfg: Settings) -> tuple[list[tuple[str, str, list[str]]], list[str]]:
    """Run `calculate_metrics` on `raw` with every step wrapped.

    Returns ([(step, first docstring line, columns it added)] in call order, the columns of the result no step
    announced) - the latter are assigned inline in `calculate_metrics` itself. A step called several times (once per
    period) is listed once, with all its columns.
    """
    calls: dict[str, tuple[str, list[str]]] = {}
    known: set[str] = set(raw.columns)

    def wrap(label: str, fn):
        @functools.wraps(fn)
        def wrapper(df, *args, **kwargs):
            before = set(df.columns)
            result = fn(df, *args, **kwargs)
            after = result if isinstance(result, pd.DataFrame) else df
            new = [c for c in after.columns if c not in before and c not in known]
            known.update(new)
            doc = (fn.__doc__ or "").strip().split("\n")[0]
            entry = calls.setdefault(label, (doc, []))
            entry[1].extend(c for c in new if c not in entry[1])
            return result

        return wrapper

    steps = {
        name: fn
        for name, fn in vars(metrics_pkg).items()
        if callable(fn) and getattr(fn, "__module__", "").startswith("fq.metrics.") and name != "calculate_metrics"
    }
    with ExitStack() as stack:
        for name, fn in steps.items():
            label = f"{fn.__module__.removeprefix('fq.')}.{fn.__name__}"
            stack.enter_context(mock.patch.object(metrics_pkg, name, wrap(label, fn)))
        out = metrics_pkg.calculate_metrics(raw, cfg)
    attributed = {c for _, cols in calls.values() for c in cols}
    inline = [c for c in out.columns if c not in raw.columns and c not in attributed]
    return [(label, doc, cols) for label, (doc, cols) in calls.items()], inline


def render(steps: list[tuple[str, str, list[str]]], inline: list[str], n_rows: int) -> str:
    """The catalogue as markdown: one section per step, in the order the pipeline runs them."""
    lines = [
        "# Metric columns by pipeline step",
        "",
        f"> Generated by `uv run python -m fq.columns` from {n_rows} companies of the cache; do not edit by hand.",
        "> A column appears under the step that first writes it, in the order `metrics.calculate_metrics` runs",
        "> them. `<p>` stands for a period (`TTM`, `Y0`, `Y1`, ...). Columns a step only updates are not repeated.",
        "> Raw columns (the Yahoo fetch) are in `settings.py` (`CONCEPTS_*`, `INFO_KEYS`); the last group is written",
        "> by `calculate_metrics` itself (model columns, `ROIC_Norm`, `Share_Reduction_Rate`, `EV`, `Market Cap`).",
        "",
    ]
    for label, doc, cols in steps:
        shown = sorted({generic(c) for c in cols})
        if not shown:
            continue
        lines += [f"## `{label}`", ""]
        if doc:
            lines += [doc, ""]
        lines += [", ".join(f"`{c}`" for c in shown), ""]
    shown = sorted({generic(c) for c in inline})
    lines += [f"## `{INLINE}`", "", ", ".join(f"`{c}`" for c in shown), ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--rows", type=int, default=200, help="companies of the cache to run through the pipeline")
    parser.add_argument("--out", type=Path, default=Path("docs/columns.md"))
    args = parser.parse_args()
    from fq.fetch import load_raw

    cfg = Settings()
    raw = load_raw(cfg.raw_path).head(args.rows)
    steps, inline = trace(raw, cfg)
    args.out.write_text(render(steps, inline, len(raw)), encoding="utf-8", newline="\n")
    print(f"{sum(len(c) for _, _, c in steps) + len(inline)} columns by {len(steps)} steps -> {args.out}")


if __name__ == "__main__":
    main()
